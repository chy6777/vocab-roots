def find_root_in_core(core):
    """在 core 中查找词根，返回 (root, meaning, match_quality)。
    match_quality: 3=精确匹配, 2=core以词根开头/结尾(余<=2), 1=包含(词根>=4且余<=2), 0=未找到。
    """
    # 1) 精确匹配
    if core in ROOTS:
        return (core, ROOTS[core], 3)

    best = None
    best_q = 0
    for rk in ROOT_KEYS:
        if rk == core:
            continue  # 已在精确匹配中处理
        # 2) core 以词根开头，余下部分 <= 2
        if core.startswith(rk) and len(core) - len(rk) <= 2 and len(rk) >= 3:
            if 2 > best_q:
                best = (rk, ROOTS[rk], 2)
                best_q = 2
        # 2) core 以词根结尾，余下部分 <= 2
        if core.endswith(rk) and len(core) - len(rk) <= 2 and len(rk) >= 3:
            if 2 > best_q:
                best = (rk, ROOTS[rk], 2)
                best_q = 2
        # 3) 词根包含在 core 中，但词根 >= 4 且余下 <= 2
        if len(rk) >= 4 and rk in core and len(core) - len(rk) <= 2:
            if 1 > best_q:
                best = (rk, ROOTS[rk], 1)
                best_q = 1
        # 3b) 3字符词根，仅当 core 较长(>=7)且余下 <= 3 时才匹配
        if len(rk) == 3 and len(core) >= 7 and rk in core and len(core) - len(rk) <= 3:
            if 1 > best_q:
                best = (rk, ROOTS[rk], 1)
                best_q = 1

    if best:
        return best
    return (None, None, 0)


def analyze_word(word):
    """分析单个英文单词，返回词根词缀解析字符串（可能为空）。
    改进：尝试多种前缀/后缀组合，按词根匹配质量评分，选最优分解。
    """
    w = word.strip().lower()

    # 基础短词 / 不可拆分的常见基础词 → 留空
    if len(w) <= 2:
        return ""
    if w in SHORT_BASIC or w in BASIC_WORDS:
        return ""

    # 收集候选前缀（所有能匹配开头的，且剩余 >= 3）
    candidate_prefixes = [(None, None, w)]  # (prefix, meaning, rest)
    for p, meaning in PREFIX_LIST:
        p_clean = p.rstrip("_")
        if len(p_clean) >= 2 and w.startswith(p_clean) and len(w) - len(p_clean) >= 3:
            candidate_prefixes.append((p_clean, meaning, w[len(p_clean):]))

    best_result = None
    best_score = -1

    for pref, pref_mean, rest in candidate_prefixes:
        # 收集候选后缀（所有能匹配 rest 结尾的，且剩余 core >= 3）
        candidate_suffixes = [(None, None, rest)]  # (suffix, meaning, core)
        for s, smeaning in SUFFIX_LIST:
            s_clean = s.rstrip("_")
            if len(s_clean) >= 2 and rest.endswith(s_clean) and len(rest) - len(s_clean) >= 3:
                candidate_suffixes.append((s_clean, smeaning, rest[:len(rest) - len(s_clean)]))

        for suf, suf_mean, core in candidate_suffixes:
            root, root_mean, q = find_root_in_core(core)

            # 评分：词根匹配质量为主，前缀/后缀为辅
            # 用浮点以便加微小罚分区分同分情况
            score = float(q * 10)
            if pref:
                score += 2 - len(pref) * 0.01  # 短前缀微优
            if suf:
                score += 1
            # 如果没有词根也没有前缀后缀，跳过
            if q == 0 and not pref and not suf:
                continue
            # 如果只有前缀但词根质量为0，降分（避免误判前缀）
            if q == 0 and pref and not suf:
                score -= 5
            # 如果只有后缀但词根质量为0，降分
            if q == 0 and suf and not pref:
                score -= 3

            if score > best_score:
                best_score = score
                best_result = (pref, pref_mean, suf, suf_mean, core, root, root_mean, q)

    if best_result is None or best_score < 0:
        return ""

    pref, pref_mean, suf, suf_mean, core, root, root_mean, q = best_result

    # 如果词根质量太低且没有前缀后缀，不输出
    if q == 0 and not pref and not suf:
        return ""
    # 如果只有低质量词根(包含匹配)且没有前缀后缀，不输出（减少误判）
    if q <= 1 and not pref and not suf:
        return ""

    # ---- 构建解析字符串 ----
    parts = []
    if pref:
        parts.append("前缀 %s-(%s)" % (pref, pref_mean))
    if root:
        parts.append("词根 %s(%s)" % (root, root_mean))
    elif core and core != w:
        parts.append("核心 %s" % core)
    if suf:
        parts.append("后缀 -%s(%s)" % (suf, suf_mean))

    if not parts:
        return ""

    result = " + ".join(parts)

    # 合成提示
    if pref and root and suf:
        result += " → 组合记忆"
    elif pref and root and not suf:
        result += " → 组合记忆"
    elif root and suf and not pref:
        result += " → 词根+后缀"
    elif pref and not root and suf:
        result += " → 前缀+核心+后缀"

    return result


def main():
    # 修复 Windows 终端中文乱码
    if sys.stdout.encoding and sys.stdout.encoding.lower() != 'utf-8':
        sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')
    if sys.stderr.encoding and sys.stderr.encoding.lower() != 'utf-8':
        sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding='utf-8', errors='replace')

    args = sys.argv[1:]
    if not args or args[0] in ("-h", "--help"):
        print("用法: python add_roots.py 输入.csv [输出.csv] [单词列序号] [新列名]")
        print("示例: python add_roots.py 单词表.csv")
        print("      python add_roots.py 单词表.csv 词根词缀版.csv 2 词根词缀")
        sys.exit(0)

    src = args[0]
    dst = args[1] if len(args) > 1 else os.path.splitext(src)[0] + "_词根词缀版.csv"
    word_col = int(args[2]) if len(args) > 2 else 0
    col_name = args[3] if len(args) > 3 else "词根词缀解析"

    # 用 utf-8-sig 读，兼容 BOM
    with open(src, "r", encoding="utf-8-sig", newline="") as f:
        reader = csv.reader(f)
        rows = list(reader)

    if not rows:
        print("空文件")
        return

    header = rows[0]
    # 在单词列后面加一列"词根词缀解析"
    new_header = header[:word_col + 1] + [col_name] + header[word_col + 1:]

    new_rows = [new_header]
    filled = 0
    for r in rows[1:]:
        if not r or len(r) <= word_col:
            new_rows.append(r + [""])
            continue
        word = r[word_col].strip()
        analysis = analyze_word(word)
        if analysis:
            filled += 1
        new_r = r[:word_col + 1] + [analysis] + r[word_col + 1:]
        new_rows.append(new_r)

    try:
        with open(dst, "w", encoding="utf-8-sig", newline="") as f:
            writer = csv.writer(f)
            writer.writerows(new_rows)
    except PermissionError:
        dst = os.path.splitext(dst)[0] + "_new.csv"
        with open(dst, "w", encoding="utf-8-sig", newline="") as f:
            writer = csv.writer(f)
            writer.writerows(new_rows)
        print("(原文件被占用, 已输出到 _new.csv)")

    total = len(rows) - 1
    print("处理完成! 共 %d 个单词, 其中 %d 个生成了词根词缀解析, 覆盖率 %.1f%%" % (total, filled, 100.0 * filled / max(total, 1)))
    print("输出文件: %s" % dst)


if __name__ == "__main__":
    main()
